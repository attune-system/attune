struct OriginalChild {
    authored_path: String,
    execution: Execution,
    result_fields: Vec<StoredSecretValue>,
    contract: ActionSchemaBinding,
    outcome: PreparedWorkflowOutcome,
}

/// A held original-source observation, not a result receipt or write permit.
/// Native output recording must consume A's opaque projection/metadata carrier
/// plus B's independent held decisions. No method here persists guessed taint.
pub struct PreparedNativeFailure {
    transaction: String,
    completed: Id,
    parent: Execution,
    workflow: WorkflowExecution,
    children: Vec<OriginalChild>,
    output_contract: ActionSchemaBinding,
    failed_tasks: Vec<String>,
    metadata: Value,
    schema_secret_paths: Vec<String>,
    fences: Vec<ApprovalEffectFence>,
}

impl PreparedNativeFailure {
    pub fn execution(&self) -> Id {
        self.parent.id
    }
    pub fn completed_execution(&self) -> Id {
        self.completed
    }
    /// Nonempty transitions need B's single-pass plan, including false decisions.
    pub fn requires_transition_plan(&self) -> Result<bool> {
        let path = self.original_task_path(self.completed)?;
        let graph = &self
            .parent
            .executable_snapshot
            .as_ref()
            .ok_or_else(changed)?
            .executable
            .workflow_definition
            .as_ref()
            .ok_or_else(changed)?
            .definition;
        let task = graph
            .pointer(path.strip_prefix("/workflow").ok_or_else(changed)?)
            .ok_or_else(changed)?;
        Ok(task.get("next").is_some_and(|value| {
            !value.is_null() && value.as_array().is_none_or(|next| !next.is_empty())
        }))
    }
    /// Compare the completion delivered to the scheduler with the exact row
    /// loaded by the source factory. A cached/model completion is not evidence.
    pub fn require_completed_execution(&self, actual: &Execution) -> Result<()> {
        let original = self
            .children
            .iter()
            .find(|source| source.execution.id == self.completed)
            .ok_or_else(changed)?;
        if actual.id != self.completed
            || serde_json::to_value(actual)? != serde_json::to_value(&original.execution)?
        {
            return Err(changed());
        }
        Ok(())
    }
    pub fn parent(&self) -> &Execution {
        &self.parent
    }
    pub fn workflow(&self) -> &WorkflowExecution {
        &self.workflow
    }
    pub fn failed_tasks(&self) -> &[String] {
        &self.failed_tasks
    }
    /// Canonical generated bytes only. These are NOT authorization/provenance.
    pub fn metadata(&self) -> &Value {
        &self.metadata
    }
    pub fn schema_secret_paths(&self) -> &[String] {
        &self.schema_secret_paths
    }
    pub fn output_contract(&self) -> &ActionSchemaBinding {
        &self.output_contract
    }
    pub fn outcomes(&self) -> impl Iterator<Item = &PreparedWorkflowOutcome> {
        self.children.iter().map(|child| &child.outcome)
    }
    pub fn source_executions(&self) -> impl Iterator<Item = &Execution> {
        self.children.iter().map(|child| &child.execution)
    }
    /// Original ciphertext/contract versions, never a claim that decrypted bytes
    /// originated in a new `/result/key` field. A can compare these observations
    /// to its independently issued source view without copying their authority.
    pub fn original_result_fields(&self, child: Id) -> Result<&[StoredSecretValue]> {
        Ok(&self
            .children
            .iter()
            .find(|source| source.execution.id == child)
            .ok_or_else(changed)?
            .result_fields)
    }
    pub fn original_contract(&self, child: Id) -> Result<&ActionSchemaBinding> {
        Ok(&self
            .children
            .iter()
            .find(|source| source.execution.id == child)
            .ok_or_else(changed)?
            .contract)
    }
    pub fn original_task_path(&self, child: Id) -> Result<&str> {
        Ok(&self
            .children
            .iter()
            .find(|source| source.execution.id == child)
            .ok_or_else(changed)?
            .authored_path)
    }
    pub fn require_original_child(
        &self,
        child: &Execution,
        contract: &ActionSchemaBinding,
        fields: &[StoredSecretValue],
    ) -> Result<()> {
        let original = self
            .children
            .iter()
            .find(|source| source.execution.id == child.id)
            .ok_or_else(changed)?;
        if serde_json::to_value(child)? != serde_json::to_value(&original.execution)?
            || contract != &original.contract
            || fields != original.result_fields.as_slice()
        {
            return Err(changed());
        }
        Ok(())
    }
    /// Pure target comparison before the owner's first mutation. Does not query
    /// or reauthorize source fields beneath workflow/cache target locks.
    pub fn require_current(
        &self,
        parent: &Execution,
        workflow: &WorkflowExecution,
        failed_tasks: &[String],
    ) -> Result<()> {
        self.require_current_rows(parent, workflow)?;
        self.require_projected_failure(failed_tasks)?;
        Ok(())
    }
    pub fn require_current_rows(
        &self,
        parent: &Execution,
        workflow: &WorkflowExecution,
    ) -> Result<()> {
        if serde_json::to_value(parent)? != serde_json::to_value(&self.parent)?
            || serde_json::to_value(workflow)? != serde_json::to_value(&self.workflow)?
        {
            return Err(changed());
        }
        Ok(())
    }
    pub fn require_projected_failure(&self, failed_tasks: &[String]) -> Result<()> {
        if failed_tasks != self.failed_tasks.as_slice() {
            return Err(changed());
        }
        Ok(())
    }
    pub fn require_metadata(&self, actual: &Value) -> Result<()> {
        if actual != &self.metadata {
            return Err(changed());
        }
        Ok(())
    }
    pub async fn ensure_fresh_on(&self, conn: &mut PgConnection) -> Result<()> {
        let current: String = sqlx::query_scalar("SELECT pg_current_xact_id()::TEXT")
            .fetch_one(&mut *conn)
            .await?;
        if current != self.transaction {
            return Err(changed());
        }
        for fence in &self.fences {
            fence.ensure_fresh_on(conn).await?;
        }
        Ok(())
    }
    pub fn ensure_fresh(&self) -> Result<()> {
        for fence in &self.fences {
            fence.ensure_fresh()?;
        }
        Ok(())
    }
}

pub struct NativeFailureMaterializationRepository;
impl NativeFailureMaterializationRepository {
    /// Owning transaction, BEFORE outer workflow advisory/target locks. IDs refer
    /// to real persisted tasks. None is only a non-native or out-of-scope graph;
    /// missing admission/schema/original source for a managed graph is an error.
    pub async fn prepare_for_completion(
        conn: &mut PgConnection,
        completed: Id,
    ) -> Result<Option<PreparedNativeFailure>> {
        let actual = ExecutionRepository::find_by_id(&mut *conn, completed)
            .await?
            .ok_or_else(changed)?;
        let Some(task) = &actual.workflow_task else {
            return Ok(None);
        };
        if task.task_index.is_some() || !terminal(actual.status) {
            return Ok(None);
        }
        let workflow = Workflows::find_by_id(&mut *conn, task.workflow_execution)
            .await?
            .ok_or_else(changed)?;
        let parent = ExecutionRepository::find_by_id(&mut *conn, workflow.execution)
            .await?
            .ok_or_else(changed)?;
        if terminal(workflow.status)
            || matches!(
                workflow.status,
                ExecutionStatus::Canceling | ExecutionStatus::Cancelled
            )
        {
            return Ok(None);
        }
        if actual.parent != Some(parent.id) {
            return Err(changed());
        }
        let Some(admission) = Authority::execution_admission(conn, parent.id).await? else {
            if parent
                .executable_snapshot
                .as_ref()
                .is_some_and(|snapshot| !snapshot.executable.action.is_adhoc)
            {
                return Err(changed());
            }
            return Ok(None);
        };
        if terminal(parent.status)
            || matches!(
                parent.status,
                ExecutionStatus::Canceling | ExecutionStatus::Cancelled
            )
        {
            return Ok(None);
        }
        let graph = &parent
            .executable_snapshot
            .as_ref()
            .ok_or_else(changed)?
            .executable
            .workflow_definition
            .as_ref()
            .ok_or_else(changed)?
            .definition;
        if !ordinary_terminal_graph(graph)? {
            return Ok(None);
        }
        if workflow.workflow_def
            != parent
                .executable_snapshot
                .as_ref()
                .ok_or_else(changed)?
                .executable
                .workflow_definition
                .as_ref()
                .ok_or_else(changed)?
                .id
        {
            return Err(changed());
        }
        let output_contract = original_contract(conn, &parent).await?;
        let mut fences = vec![Authority::retained_admission_fence(conn, admission.id).await?];
        let rows = ExecutionRepository::find_by_parent(&mut *conn, parent.id).await?;
        if rows.len() > MAX_CHILDREN {
            return Err(changed());
        }
        let mut children = Vec::new();
        let mut by_name = BTreeMap::new();
        let mut held_bytes = 0;
        add_held_bytes(&mut held_bytes, &parent)?;
        add_held_bytes(&mut held_bytes, &workflow)?;
        add_held_bytes(&mut held_bytes, &output_contract)?;
        for row in rows {
            let Some(metadata) = &row.workflow_task else {
                continue;
            };
            if metadata.workflow_execution != workflow.id {
                return Err(changed());
            }
            // Iteration and retry selection remain B's separate owning paths.
            if metadata.task_index.is_some()
                || metadata.retry_count != 0
                || by_name.contains_key(&metadata.task_name)
                || !terminal(row.status)
            {
                return Ok(None);
            }
            let outcome = Inputs::prepare_outcome(conn, parent.id, row.id).await?;
            let authored_path = super::declared_input_materialization::DeclaredInputMaterializationRepository::workflow_task_site_path(
                conn, parent.id, &metadata.task_name, &row.action_ref,
            ).await?;
            let source = Authority::execution_admission(conn, row.id)
                .await?
                .ok_or_else(changed)?;
            fences.push(Authority::retained_admission_fence(conn, source.id).await?);
            let contract = original_contract(conn, &row).await?;
            let result_fields =
                Secrets::find_stored_by_entity(&mut *conn, ENTITY_EXECUTION_RESULT, row.id).await?;
            let held = ExecutionRepository::find_by_id(&mut *conn, row.id)
                .await?
                .ok_or_else(changed)?;
            if serde_json::to_value(&held)? != serde_json::to_value(&row)? {
                return Err(changed());
            }
            add_held_bytes(&mut held_bytes, &row)?;
            add_held_bytes(&mut held_bytes, &contract)?;
            for field in &result_fields {
                add_held_bytes(
                    &mut held_bytes,
                    &(
                        &field.json_path,
                        &field.encrypted_value,
                        &field.encryption_key_hash,
                        &field.source_kind,
                        &field.source_ref,
                    ),
                )?;
            }
            by_name.insert(metadata.task_name.clone(), (row.id, failure(row.status)));
            children.push(OriginalChild {
                authored_path,
                execution: row,
                result_fields,
                contract,
                outcome,
            });
        }
        if !children
            .iter()
            .any(|source| source.execution.id == completed)
        {
            return Err(changed());
        }
        let mut failed_tasks = workflow.failed_tasks.clone();
        let mut unique = BTreeSet::new();
        for name in &failed_tasks {
            if !unique.insert(name.clone()) || !by_name.get(name).is_some_and(|(_, failed)| *failed)
            {
                return Err(changed());
            }
        }
        if failure(actual.status) && unique.insert(task.task_name.clone()) {
            failed_tasks.push(task.task_name.clone());
        }
        if failed_tasks.is_empty() {
            return Ok(None);
        }
        // Another completion not yet reflected in this workflow needs its own
        // same-advance owner; do not invent that task's scheduler outcome here.
        if by_name
            .iter()
            .any(|(name, (_, failed))| *failed && !unique.contains(name))
        {
            return Ok(None);
        }
        let metadata = failure_metadata(&failed_tasks);
        bounded(&metadata)?;
        let schema_secret_paths = output_contract
            .output
            .as_ref()
            .map(|contract| {
                let compiled = CompiledContract::new(contract).map_err(|_| changed())?;
                Ok::<_, Error>(compiled.secret_paths(&metadata).unwrap_or_else(|_| {
                    if compiled.declares_secrets() {
                        vec![String::new()]
                    } else {
                        Vec::new()
                    }
                }))
            })
            .transpose()?
            .unwrap_or_default();
        let plan = PreparedNativeFailure {
            transaction: sqlx::query_scalar("SELECT pg_current_xact_id()::TEXT")
                .fetch_one(&mut *conn)
                .await?,
            completed,
            parent,
            workflow,
            children,
            output_contract,
            failed_tasks,
            metadata,
            schema_secret_paths,
            fences,
        };
        plan.ensure_fresh_on(conn).await?;
        Ok(Some(plan))
    }
}

async fn original_contract(
    conn: &mut PgConnection,
    execution: &Execution,
) -> Result<ActionSchemaBinding> {
    let binding = Schemas::find(conn, BindingOwner::Execution, execution.id)
        .await?
        .ok_or_else(changed)?;
    binding.validate()?;
    let snapshot = execution.executable_snapshot.as_ref().ok_or_else(changed)?;
    if execution.action != Some(snapshot.executable.action.id)
        || execution.action_ref != snapshot.executable.action.r#ref
        || execution.pack_release != Some(snapshot.release.id)
        || execution.pack_release_digest.as_deref() != Some(snapshot.release.digest.as_str())
        || binding.input.source
            != (SourceIdentity::Released {
                component_ref: snapshot.executable.action.r#ref.clone(),
                release_id: snapshot.release.id,
                release_digest: snapshot.release.digest.clone(),
            })
    {
        return Err(changed());
    }
    Ok(binding)
}

fn terminal(status: ExecutionStatus) -> bool {
    matches!(
        status,
        ExecutionStatus::Completed | ExecutionStatus::Failed | ExecutionStatus::Timeout
    )
}
fn failure(status: ExecutionStatus) -> bool {
    matches!(status, ExecutionStatus::Failed | ExecutionStatus::Timeout)
}
fn failure_metadata(tasks: &[String]) -> Value {
    serde_json::json!({"error":format!("Workflow failed: {} task(s) failed: {}", tasks.len(), tasks.join(", ")),"succeeded":false})
}
fn ordinary_terminal_graph(graph: &Value) -> Result<bool> {
    bounded(graph)?;
    let mut pending = vec![graph];
    while let Some(node) = pending.pop() {
        if ["with_items", "iterate_cache", "wait_for"]
            .iter()
            .any(|field| node.get(*field).is_some_and(|value| !value.is_null()))
        {
            return Ok(false);
        }
        if let Some(next) = node.get("next").and_then(Value::as_array) {
            if next.iter().any(|next| {
                next.get("do").is_some_and(|tasks| {
                    !tasks.is_null() && tasks.as_array().is_none_or(|tasks| !tasks.is_empty())
                })
            }) {
                return Ok(false);
            }
        }
        if let Some(tasks) = node.get("tasks").filter(|value| !value.is_null()) {
            match tasks {
                Value::Array(tasks) => pending.extend(tasks),
                Value::Object(tasks) => pending.extend(tasks.values()),
                _ => return Err(changed()),
            }
        }
    }
    Ok(true)
}
fn bounded(value: &Value) -> Result<()> {
    if serde_json::to_vec(value)?.len() > MAX_BYTES {
        return Err(changed());
    }
    let mut pending = vec![(value, 0)];
    let mut count = 0;
    while let Some((value, depth)) = pending.pop() {
        count += 1;
        if count > 16384 || depth > 64 {
            return Err(changed());
        }
        match value {
            Value::Object(values) => {
                pending.extend(values.values().map(|value| (value, depth + 1)))
            }
            Value::Array(values) => pending.extend(values.iter().map(|value| (value, depth + 1))),
            _ => {}
        }
    }
    Ok(())
}
fn add_held_bytes(bytes: &mut usize, value: &impl serde::Serialize) -> Result<()> {
    *bytes = bytes
        .checked_add(serde_json::to_vec(value)?.len())
        .filter(|bytes| *bytes <= MAX_BYTES)
        .ok_or_else(changed)?;
    Ok(())
}
fn changed() -> Error {
    Error::PermissionDenied("Native failure original source changed or is unavailable".into())
}

