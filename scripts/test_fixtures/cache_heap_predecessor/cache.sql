CREATE OR REPLACE FUNCTION cache_entry_staging_only()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM cache_generation WHERE id = NEW.generation AND status = 'staging'
    ) THEN
        RAISE EXCEPTION 'cache entry generation must be staging';
    END IF;
    RETURN NEW;
END; $$;

