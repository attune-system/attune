-- Fixed queue configuration is admitted separately from item contributors and
-- execution API permissions. Values are encrypted, bound to their owning item,
-- and never reselected from current Keys/configuration during dispatch/retry.
CREATE TABLE work_queue_item_configuration_input (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Independent receipt retention: deleting the source item does not erase
    -- accepted input evidence still used by an execution.
    item BIGINT NOT NULL UNIQUE,
    policy_revision BIGINT NOT NULL REFERENCES pack_runtime_policy_revision(id) ON DELETE RESTRICT,
    configuration_revision BIGINT REFERENCES component_configuration_revision(id) ON DELETE RESTRICT,
    binding JSONB NOT NULL CHECK (octet_length(binding::TEXT) <= 1048576),
    binding_digest TEXT NOT NULL,
    encrypted_context JSONB NOT NULL CHECK (octet_length(encrypted_context::TEXT) <= 2097152),
    encryption_key_hash TEXT NOT NULL
);
CREATE INDEX work_queue_configuration_input_policy ON work_queue_item_configuration_input(policy_revision);
CREATE INDEX work_queue_configuration_input_revision ON work_queue_item_configuration_input(configuration_revision);
CREATE TRIGGER guard_work_queue_configuration_input BEFORE UPDATE ON work_queue_item_configuration_input
    FOR EACH ROW EXECUTE FUNCTION guard_runtime_schema_binding();

CREATE TABLE runtime_input_queue_configuration_reference (
    receipt BIGINT NOT NULL REFERENCES runtime_input_receipt(id) ON DELETE CASCADE,
    input BIGINT NOT NULL REFERENCES work_queue_item_configuration_input(id) ON DELETE RESTRICT,
    PRIMARY KEY(receipt,input)
);
CREATE INDEX runtime_input_queue_configuration_input ON runtime_input_queue_configuration_reference(input);
CREATE TRIGGER guard_runtime_input_queue_configuration_reference BEFORE UPDATE ON runtime_input_queue_configuration_reference
    FOR EACH ROW EXECUTE FUNCTION guard_runtime_schema_binding();
CREATE TRIGGER aaa_file_evidence_entry BEFORE DELETE ON work_queue_item_configuration_input
    FOR EACH STATEMENT EXECUTE FUNCTION file_evidence_delete_entry();
CREATE TRIGGER file_evidence_guard BEFORE DELETE ON work_queue_item_configuration_input
    FOR EACH ROW EXECUTE FUNCTION file_evidence_guard_delete('work_queue_item_configuration_input','id');

CREATE FUNCTION guard_queue_configuration_reference() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        IF NOT file_evidence_graph_held(false) THEN
            RAISE EXCEPTION 'Queue input reference requires graph admission before source protection';
        END IF;
        RETURN NEW;
    END IF;
    IF NOT file_evidence_graph_held(true) THEN
        RAISE EXCEPTION 'Queue input reference reclamation requires exclusive graph admission';
    END IF;
    IF file_evidence_pinned('runtime_input_receipt',OLD.receipt) THEN RETURN NULL; END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER queue_configuration_reference_admission BEFORE INSERT ON runtime_input_queue_configuration_reference
    FOR EACH ROW EXECUTE FUNCTION guard_queue_configuration_reference();
CREATE TRIGGER aaa_file_evidence_entry BEFORE DELETE ON runtime_input_queue_configuration_reference
    FOR EACH STATEMENT EXECUTE FUNCTION file_evidence_delete_entry();
CREATE TRIGGER file_evidence_guard BEFORE DELETE ON runtime_input_queue_configuration_reference
    FOR EACH ROW EXECUTE FUNCTION guard_queue_configuration_reference();
