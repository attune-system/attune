CREATE TABLE pack_runtime_preparation_attempt (
    install BIGINT PRIMARY KEY REFERENCES pack_install(id) ON DELETE CASCADE,
    activation BIGINT NOT NULL REFERENCES pack_install(id) ON DELETE CASCADE,
    release_digest TEXT NOT NULL,
    requests JSONB NOT NULL,
    scopes JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    builder_incarnation UUID,
    prepared JSONB
);

CREATE TABLE pack_release_runtime_preparation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release BIGINT NOT NULL REFERENCES pack_release(id) ON DELETE CASCADE,
    component_kind TEXT NOT NULL CHECK (component_kind IN ('action', 'sensor')),
    component_ref TEXT NOT NULL,
    prepared JSONB NOT NULL
);
CREATE INDEX pack_release_runtime_preparation_lookup
    ON pack_release_runtime_preparation (release, component_kind, component_ref, id DESC);
